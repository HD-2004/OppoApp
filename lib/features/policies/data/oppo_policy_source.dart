Ốp Pờ luôn đặt quyền lợi của ứng viên lên hàng đầu. Đọc kỹ để biết bạn được bảo vệ như thế nào nhé!
1. Đăng ký & hồ sơ cá nhân
1.1 Điều kiện đăng ký
Từ đủ 18 tuổi trở lên.
Sử dụng số điện thoại hoặc email cá nhân thực để xác minh tài khoản.
Mỗi cá nhân chỉ được tạo một tài khoản ứng viên duy nhất.
1.2 Yêu cầu hồ sơ
Bắt buộc: Ảnh đại diện rõ mặt (không đeo kính tối, không đội mũ che mặt), họ tên đầy đủ, số điện thoại liên hệ, khu vực làm việc mong muốn.
Khuyến khích bổ sung: Kinh nghiệm làm việc F&B (nếu có), kỹ năng đặc thù (pha chế, phục vụ, bếp...), lịch làm việc ưa thích.
Thông tin hồ sơ phải trung thực. Nếu phát hiện gian lận (khai kinh nghiệm giả, sử dụng ảnh người khác...), tài khoản sẽ bị khóa vĩnh viễn.
2. Quy trình ứng tuyển
Ứng viên tìm kiếm tin phù hợp và bấm Ứng tuyển hoặc nhận được lời mời từ nhà tuyển dụng.
Nhà tuyển dụng xem xét hồ sơ và xác nhận/từ chối trong thời hạn tin còn hiệu lực (job Gấp).
Nếu được chấp nhận, ứng viên nhận thông báo qua app, SMS hoặc email kèm thông tin chi tiết về ca làm việc (job Gấp).
Ứng viên xác nhận lại lịch làm việc trong thời gian quy định của job Gấp khi nhận thông báo.
Đến đúng giờ, đúng địa điểm và hoàn thành ca làm việc.
Sau ca, đánh giá nhà tuyển dụng để giúp cộng đồng Ốp Pờ ngày càng tốt hơn.
3. Quyền lợi của ứng viên
Sử dụng toàn bộ tính năng nền tảng hoàn toàn miễn phí, không mất bất kỳ khoản phí nào.
Được xem đầy đủ thông tin về công việc trước khi quyết định ứng tuyển: địa điểm, giờ giấc, mức lương, mô tả công việc.
Được Ốp Pờ hỗ trợ hòa giải nếu xảy ra tranh chấp với nhà tuyển dụng về lương hoặc điều kiện làm việc.
Được bảo vệ thông tin cá nhân theo Chính sách Bảo mật của Ốp Pờ.
Được báo cáo nhà tuyển dụng vi phạm (không trả lương, môi trường không an toàn, v.v.) và nhận phản hồi trong vòng 48 giờ làm việc.

