CHÍNH SÁCH 04: 
DÀNH CHO NHÀ TUYỂN DỤNG
Áp dụng cho: Doanh nghiệp & hộ kinh doanh F&B
Nền tảng: Web & App
Phí đăng ký: Miễn phí

Ốp Pờ giúp bạn tìm đúng người, đúng ca, đúng lúc. Dưới đây là những điều bạn cần biết để sử dụng nền tảng hiệu quả nhất.
1. Đăng ký tài khoản nhà tuyển dụng
1.1 Thông tin cần thiết khi đăng ký
Tên doanh nghiệp hoặc hộ kinh doanh (phải khớp với giấy tờ đăng ký kinh doanh).
Địa chỉ cơ sở kinh doanh chính xác.
Mã số thuế (với doanh nghiệp) hoặc CMND/CCCD của chủ hộ kinh doanh (với hộ cá thể).
Số điện thoại và email liên hệ chính thức.
Tên và thông tin người đại diện quản lý tài khoản.
1.2 Quy trình xét duyệt
Sau khi đăng ký, hồ sơ nhà tuyển dụng sẽ được Ốp Pờ xem xét và phê duyệt trong vòng 24 giờ làm việc (không tính thứ 7, CN và ngày lễ).
Ốp Pờ có thể yêu cầu bổ sung giấy tờ xác minh nếu cần thiết.
Tài khoản bị từ chối sẽ được thông báo lý do và có thể nộp lại sau khi bổ sung đầy đủ.
2. Đăng tin tuyển dụng
2.1 Miễn phí không giới hạn
Nhà tuyển dụng được đăng tin tuyển dụng thông thường hoàn toàn miễn phí, không giới hạn số lượng tin cùng lúc.
2.2 Thông tin bắt buộc trong tin tuyển dụng
Tên vị trí tuyển dụng cụ thể (ví dụ: Phục vụ, Thu ngân, Pha chế, Bếp...).
Số lượng nhân sự cần tuyển.
Thời gian làm việc: ngày, giờ bắt đầu và kết thúc ca.
Địa điểm làm việc chính xác (địa chỉ đầy đủ).
Mức lương hoặc khoảng lương cụ thể (bắt buộc: không được ghi “thỏa thuận” mà không kèm mức tham khảo).
Mô tả công việc và yêu cầu cơ bản (trang phục, kinh nghiệm, độ tuổi nếu có).
2.3 Điều cấm trong nội dung tin
Đăng tin không có nhu cầu tuyển dụng thực sự (tin mồi, lấy thông tin ứng viên).
Thông tin lương, công việc, địa điểm sai lệch so với thực tế.
Yêu cầu ứng viên nộp tiền cọc, phí gia nhập hoặc bất kỳ khoản phí nào.
Ngôn ngữ phân biệt đối xử về giới tính, ngoại hình, sắc tộc, tôn giáo.
3. Quy trình tuyển dụng trên nền tảng
Đăng tin → hệ thống tự động gợi ý ứng viên phù hợp.
Nhà tuyển dụng xem xét hồ sơ → Xác nhận hoặc Từ chối ứng viên.
Ứng viên được thông báo và xác nhận lịch làm việc.
Nhà tuyển dụng nhận danh sách nhân sự đã xác nhận ca.
Sau ca, đánh giá ứng viên (chất lượng, thái độ, đúng giờ).
Thanh toán lương trực tiếp cho ứng viên theo thỏa thuận.
4. Quyền lợi của nhà tuyển dụng
Tiếp cận kho hồ sơ ứng viên F&B đã được xác minh thông tin cơ bản.
Lọc ứng viên theo kỹ năng, kinh nghiệm, khu vực, điểm uy tín và lịch rảnh.
Quản lý toàn bộ quy trình tuyển dụng trực quan trên dashboard.
Đánh giá và lưu danh sách ứng viên tin cậy để tái sử dụng cho lần sau.
Được hỗ trợ hòa giải từ Ốp Pờ nếu xảy ra sự cố với ứng viên.
5. Trách nhiệm của nhà tuyển dụng
Đảm bảo môi trường làm việc an toàn, phù hợp với quy định lao động Việt Nam.
Trả lương đúng mức đã cam kết trong tin tuyển dụng và đúng hạn (cuối ca hoặc theo thỏa thuận).
Có mặt hoặc cử người đại diện tiếp nhận ứng viên đúng giờ đã hẹn.
