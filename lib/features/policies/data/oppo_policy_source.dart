Mục tiêu: Đảm bảo môi trường tuyển dụng lành mạnh, an toàn & tin cậy

Ốp Pờ xây dựng cộng đồng tuyển dụng dựa trên sự tin tưởng. Chúng mình cam kết xử lý nghiêm mọi hành vi gian lận hoặc gây hại để bảo vệ tất cả người dùng.
1. Phân loại vi phạm
🔴 Vi phạm Cấp độ 1 - Nghiêm trọng (Khóa tài khoản vĩnh viễn)
Đăng tin giả, lừa đảo ứng viên: không có nhu cầu tuyển dụng thực sự, mô tả công việc hoàn toàn sai lệch.
Yêu cầu ứng viên đặt cọc, nộp tiền gia nhập hoặc bất kỳ khoản phí nào dưới bất kỳ hình thức nào.
Quấy rối tình dục, có hành vi bạo lực hoặc đe dọa với ứng viên/nhà tuyển dụng.
Tạo nhiều tài khoản giả để gian lận, thao túng điểm uy tín hoặc hệ thống đánh giá.
Sử dụng nền tảng để lừa đảo tài chính hoặc thu thập thông tin cá nhân trái phép.
Đăng tải nội dung vi phạm pháp luật: kích động bạo lực, nội dung khiêu dâm, nội dung phân biệt đối xử nghiêm trọng.

🟡 Vi phạm Cấp độ 2 - Trung bình (Cảnh cáo + Tạm khóa 7 ngày)
Thông tin tuyển dụng sai lệch ở một số điểm (lương thực tế thấp hơn đăng, địa chỉ không khớp...).
Không phản hồi ứng viên sau khi đã match, bỏ mặc không xác nhận lịch.
Hủy ca trong vòng 4 tiếng trước giờ làm nhiều lần (từ 3 lần trong 30 ngày).
Đánh giá sai sự thật về ứng viên/nhà tuyển dụng với mục đích phá hoại.

🟢 Vi phạm Cấp độ 3 - Nhẹ (Nhắc nhở qua email/app)
Hồ sơ thiếu thông tin bắt buộc hoặc ảnh đại diện không đạt tiêu chuẩn.
Nội dung tin tuyển dụng chưa đầy đủ theo quy định.
Hủy ca muộn lần đầu (chưa đến mức cảnh cáo chính thức).
Không cập nhật trạng thái tin khi đã tuyển đủ người.
2. Quy trình xử lý vi phạm
1. Tiếp nhận báo cáo/Hệ thống phát hiện vi phạm - Ngay lập tức
2. Xem xét bằng chứng và xác minh thông tin từ các bên liên quan - Trong 24 giờ làm việc
3. Ra quyết định xử lý theo phân loại vi phạm - Trong 48 giờ làm việc
4. Thông báo quyết định đến người dùng vi phạm qua email + app - Ngay sau khi có quyết định
5. Thực thi: nhắc nhở / tạm khóa / xóa tài khoản - Ngay lập tức sau bước 4

3. Khiếu nại quyết định xử lý
Người dùng có quyền khiếu nại quyết định xử lý tài khoản trong vòng 5 ngày làm việc kể từ ngày nhận thông báo.
Yêu cầu khiếu nại gửi qua email hỗ trợ chính thức với tiêu đề: "Khiếu nại xử lý tài khoản – [Tên tài khoản] – [Ngày nhận quyết định]".
Đính kèm bằng chứng phản bác (ảnh chụp màn hình, tin nhắn, video...) để được xem xét đầy đủ.
Ốp Pờ sẽ có phản hồi chính thức trong vòng 3 ngày làm việc kể từ khi nhận đủ hồ sơ.
Quyết định sau khiếu nại là quyết định cuối cùng từ phía Ốp Pờ.
4. Báo cáo vi phạm
Nếu bạn phát hiện hành vi vi phạm từ người dùng khác, hãy:
Nhấn nút Báo cáo ngay trên tin tuyển dụng, hồ sơ ứng viên hoặc tin nhắn liên quan.
Chọn loại vi phạm và mô tả ngắn gọn sự việc.
Đính kèm bằng chứng nếu có (ảnh chụp màn hình, video...).

Mọi báo cáo đều được xem xét nghiêm túc và bảo mật danh tính người báo cáo. Chúng mình cảm ơn bạn đã giúp Ốp Pờ trở thành nền tảng an toàn và tin cậy hơn!

